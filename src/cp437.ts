/**
 * CP437（IBM PC 原始 OEM 字符集）解码。
 *
 * ZIP 规范（APPNOTE 附录 D）：未置 EFS 位（bit11）的文件名按 CP437 解释。
 * 0x00-0x7F 与 ASCII 一致；0x80-0xFF 是西文字母、制表线与数学符号的固定映射。
 * 本表为 CP437 高半区的权威映射，测试用独立权威源复核（见 tests/encoding.test.ts）。
 *
 * 只做解码：本库写侧的策略是"ASCII 原样 / 非 ASCII 一律 UTF-8 + EFS 位"，
 * 不产出 CP437 编码的名字（任务书停止规则：CP437 之外的 OEM 编码不做）。
 */

/** CP437 0x80..0xFF 的 128 个码点，按码位顺序排列。
 *  注意倒数第二项（0xFE）是 U+00A0 不换行空格 NBSP，不是普通空格。 */
const HIGH = [
  'Ç', 'ü', 'é', 'â', 'ä', 'à', 'å', 'ç', 'ê', 'ë', 'è', 'ï', 'î', 'ì', 'Ä', 'Å',
  'É', 'æ', 'Æ', 'ô', 'ö', 'ò', 'û', 'ù', 'ÿ', 'Ö', 'Ü', '¢', '£', '¥', '₧', 'ƒ',
  'á', 'í', 'ó', 'ú', 'ñ', 'Ñ', 'ª', 'º', '¿', '⌐', '¬', '½', '¼', '¡', '«', '»',
  '░', '▒', '▓', '│', '┤', '╡', '╢', '╖', '╕', '╣', '║', '╗', '╝', '╜', '╛', '┐',
  '└', '┴', '┬', '├', '─', '┼', '╞', '╟', '╚', '╔', '╩', '╦', '╠', '═', '╧', '╨',
  '╤', '╥', '╙', '╘', '╒', '╓', '╫', '╪', '┘', '┌', '█', '▄', '▌', '▐', '▀', 'α',
  'ß', 'Γ', 'π', 'Σ', 'σ', 'µ', 'τ', 'Φ', 'Θ', 'Ω', 'δ', '∞', 'φ', 'ε', '∩', '≡',
  '±', '≥', '≤', '⌠', '⌡', '÷', '≈', '°', '∙', '·', '√', 'ⁿ', '²', '■', ' ', '▲',
] as const;

/** 查表：字节 → 码点。0x00-0x7F 走 ASCII 直映射（0x7F 按原样保留）。 */
export function cp437Decode(bytes: Uint8Array): string {
  let s = '';
  for (let i = 0; i < bytes.length; i++) {
    const b = bytes[i]!;
    if (b < 0x80) {
      s += String.fromCharCode(b);
    } else {
      s += HIGH[b - 0x80]!;
    }
  }
  return s;
}
